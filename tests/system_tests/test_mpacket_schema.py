"""
Round-trip tests for the MPacket envelope schema (core/packets/m_packet.py).

This is a pure unit test - no Redis/UDS/shared memory involved, since
MPacket itself is just a data envelope plus (de)serialization, not a
process or a channel. It lives here in tests/system_tests/ (rather than
tests/unit_tests/) because it's step one of the inter-process protocol
unification from the architecture review - the rest of that work
(BaseWorker's register_handler/dispatch, the per-channel migrations) will
land in this same folder.
"""
from core.packets.m_packet import MPacket


def test_create_populates_all_fields():
    packet = MPacket.create(
        "Analyser", "Executer", "BUY",
        errornum=0, msg="entry order",
        payload={"symbol": "BTCUSDT", "quantity": 0.01},
    )

    assert packet.sender == "Analyser"
    assert packet.to == "Executer"
    assert packet.type == "BUY"
    assert packet.errornum == 0
    assert packet.msg == "entry order"
    assert packet.payload == {"symbol": "BTCUSDT", "quantity": 0.01}
    assert packet.timestamp  # non-empty, auto-generated by create()


def test_create_defaults_errornum_msg_and_payload():
    packet = MPacket.create("DataPipeline", "ALL", "dollar_bar")

    assert packet.errornum == 0
    assert packet.msg == ""
    # Never None - callers (handlers) shouldn't need a `payload or {}` guard.
    assert packet.payload == {}


def test_to_json_from_json_round_trip_preserves_everything():
    original = MPacket.create(
        "Analyser", "Executer", "SMART_EXIT",
        errornum=1, msg="time stop",
        payload={"symbol": "ETHUSDT", "quantity": 0.5, "side": "SELL"},
    )

    restored = MPacket.from_json(original.to_json())

    assert restored.sender == original.sender
    assert restored.to == original.to
    assert restored.type == original.type
    assert restored.errornum == original.errornum
    assert restored.msg == original.msg
    assert restored.payload == original.payload
    assert restored.timestamp == original.timestamp


def test_to_dict_uses_sender_key_not_from():
    """
    `from` is a reserved Python keyword and can never be a valid attribute
    name (`self.from = ...` is a SyntaxError), so the wire format uses
    "sender" instead. Pinning this down here: if something later tries to
    reintroduce a "from" key on the wire, this test catches the mismatch.
    """
    packet = MPacket.create("Executer", "Manager", "log", msg="hello")
    data = packet.to_dict()

    assert "sender" in data
    assert "from" not in data


def test_from_dict_defaults_are_safe_for_missing_fields():
    """
    A partially-formed dict (an old message shape still in flight during a
    rollout, or a bug upstream) should degrade to safe defaults rather than
    raising - MPacket is meant to be the forgiving edge of the system, not
    another place a malformed message can crash a worker.
    """
    restored = MPacket.from_dict({"type": "heartbeat"})

    assert restored.sender == "Unknown"
    assert restored.to == "Unknown"
    assert restored.msg == ""
    assert restored.payload == {}
    assert restored.errornum == 0
